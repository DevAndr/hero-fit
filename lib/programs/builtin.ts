export function programBySlug(slug: string): BuiltinProgram | null {
  return BUILTIN_PROGRAMS.find((p) => p.slug === slug) ?? null;
}

/** Плоский список дней всех программ — для сида (порядок модуля). */
export function seedDays(): {
  program: string;
  name: string;
  description: string;
  exercises: [name: string, sets: number, reps: number][];
}[] {
  return BUILTIN_PROGRAMS.flatMap((p) =>
    p.days.map((d) => ({ program: p.program, name: d.name, description: d.description, exercises: d.exercises })),
  );
}
